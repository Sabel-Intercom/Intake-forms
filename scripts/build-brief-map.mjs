#!/usr/bin/env node
// node scripts/build-brief-map.mjs           prints the map
// node scripts/build-brief-map.mjs --write   rewrites it inside SabelInternalOps.html
//
// The build brief in Internal Ops turns a client's saved readiness answers into
// a config sheet. To read those answers it needs to know every question in the
// form: its id, wording, which fields it saves, and when it is shown. This
// script lifts that from SabelReadinessCheck.html (the only place questions are
// written) and writes it between BRIEF-FORM:BEGIN and :END in Internal Ops.
//
// Run it with --write whenever a question is added, removed or reworded in the
// form. tests/build-brief.test.mjs fails when the two have drifted.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const FORM = path.join(ROOT, 'SabelReadinessCheck.html');
export const OPS = path.join(ROOT, 'SabelInternalOps.html');
export const BEGIN = '/* BRIEF-FORM:BEGIN (generated by scripts/build-brief-map.mjs from SabelReadinessCheck.html; do not edit by hand) */';
export const END = '/* BRIEF-FORM:END */';

export function formMap(html) {
  const a = html.indexOf('const O = {');
  const b = html.indexOf('const SECTIONS = [');
  const e = html.indexOf('\n];', b);
  if (a < 0 || b < 0 || e < 0) throw new Error('Could not find the question list in the readiness form');
  const v = (html.match(/const FORM_V = '([^']+)'/) || [])[1] || '';
  const { SECTIONS } = new Function('state', html.slice(a, e + 3) + '\nreturn {SECTIONS};')({ data: {}, reps: {}, projectType: '' });
  const sections = SECTIONS.map(s => {
    const sec = { id: s.id, title: s.title, items: [] };
    if (s.scope) sec.scope = s.scope;
    s.items.filter(i => i.t !== 'note').forEach(it => {
      const o = { id: it.id, t: it.t, q: it.q };
      if (it.scope) o.scope = it.scope;
      if (it.ind) o.ind = [].concat(it.ind);
      if (it.when) {
        // Shown only when one of these is ticked in question a0.
        o.when = [...String(it.when).matchAll(/picked\('([^']+)'\)/g)].map(m => m[1]);
        if (!o.when.length) throw new Error('Question ' + it.id + ' has a show rule this script cannot read');
      }
      if (it.f) {
        o.f = [];
        it.f.forEach(f => { o.f.push([f[0], f[1]]); if (f[4] && f[4].id) o.f.push([f[4].id, f[4].label || 'More detail']); });
      }
      if (it.rep) o.rep = { id: it.rep.id, cols: it.rep.cols.map(c => [c[0], c[1]]) };
      if (it.multi) o.multi = { id: it.multi.id, other: !!it.multi.other };
      sec.items.push(o);
    });
    return sec;
  });
  return { v, sections };
}

export function block(html) {
  return BEGIN + '\nconst BRIEF_FORM = ' + JSON.stringify(formMap(html)) + ';\n' + END;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = block(fs.readFileSync(FORM, 'utf8'));
  if (process.argv.includes('--write')) {
    const ops = fs.readFileSync(OPS, 'utf8');
    const i = ops.indexOf(BEGIN), j = ops.indexOf(END);
    if (i < 0 || j < 0) throw new Error('BRIEF-FORM markers not found in SabelInternalOps.html');
    fs.writeFileSync(OPS, ops.slice(0, i) + out + ops.slice(j + END.length));
    console.log('Updated the question map in SabelInternalOps.html');
  } else {
    console.log(out);
  }
}
